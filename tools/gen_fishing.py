#!/usr/bin/env python3
"""Generate src/generated/fishing.inc from data/'s five phoenix_fish*.tsv files.

With --check DIR, check DIR's files by the same rules and write nothing: refresh.sh does, before it copies a Phoenix
refresh's fishing files into data/.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent / 'phoenix'))
from fishing import HEADERS  # noqa: E402

BYTE, WORD = 0xFF, 0xFFFF
# Each file's columns by their largest value; None for a float, a list for a space-separated list of number pairs.
LIMITS = {
    'phoenix_fish.tsv': [WORD, BYTE, BYTE, 1, 1, 1, 1, 1, WORD, WORD],
    'phoenix_fish_areas.tsv': [WORD, BYTE, 2, BYTE, BYTE, None, None, None, WORD, 'points'],
    'phoenix_fish_groups.tsv': [WORD, WORD],
    'phoenix_fish_baits.tsv': [WORD, 1, 1, 'pairs'],
    'phoenix_fish_rods.tsv': [WORD, BYTE, 1],
}


class DataError(ValueError):
    pass


def parse(name: str, text: str) -> list:
    lines = text.splitlines()
    if not lines or lines[0] != HEADERS[name]:
        raise DataError(f'{name} does not start with its header')
    rows = []
    for number, line in enumerate(lines[1:], 2):
        fields = line.split('\t')
        if len(fields) != len(LIMITS[name]):
            raise DataError(f'{name} line {number} has {len(fields)} fields')
        row = []
        for field, limit in zip(fields, LIMITS[name]):
            if limit is None:
                row.append(float(field))
            elif isinstance(limit, str):
                cast = float if limit == 'points' else int
                row.append([tuple(cast(v) for v in pair.split(':')) for pair in field.split()])
            else:
                value = int(field)
                if not 0 <= value <= limit:
                    raise DataError(f'{name} line {number}: {value} does not fit its field')
                row.append(value)
        rows.append(row)
    return rows


def load_folder(folder: pathlib.Path) -> dict:
    data = {name: parse(name, (folder / name).read_text(encoding='utf-8')) for name in HEADERS}
    items = {f[0] for f in data['phoenix_fish.tsv']}
    for group, item in data['phoenix_fish_groups.tsv']:
        if item not in items:
            raise DataError(f'group {group} names {item}, which the server does not load')
    for bait in data['phoenix_fish_baits.tsv']:
        for item, _ in bait[3]:
            if item not in items:
                raise DataError(f'bait {bait[0]} names {item}, which the server does not load')
    return data


def generate(data: dict) -> str:
    lines = ['// Generated by tools/gen_fishing.py from data/phoenix_fish*.tsv. Do not edit.', 'const FishRow kFish[] = {']
    lines += ['    {' + ', '.join(map(str, f)) + '},' for f in data['phoenix_fish.tsv']]
    lines += ['};', 'const FishAreaRow kFishAreas[] = {']
    points = []
    for zone, area, kind, height, radius, x, y, z, group, shape in data['phoenix_fish_areas.tsv']:
        lines.append(f'    {{{zone}, {area}, {kind}, {height}, {radius}, {x:.3f}f, {y:.3f}f, {z:.3f}f, {group}, '
                     f'{len(points)}, {len(shape)}}},')
        points += shape
    # A zero-length array is not C++: a spare row keeps each one whole.
    lines += ['};', 'const AreaPoint kAreaPoints[] = {']
    lines += [f'    {{{x:.3f}f, {z:.3f}f}},' for x, z in points] or ['    {0.0f, 0.0f},']
    lines += ['};', 'const GroupFishRow kGroupFish[] = {']
    lines += [f'    {{{g}, {i}}},' for g, i in data['phoenix_fish_groups.tsv']]
    lines += ['};', 'const BaitRow kBaits[] = {']
    affinities = []
    for bait, lure, shellfish, pairs in data['phoenix_fish_baits.tsv']:
        lines.append(f'    {{{bait}, {lure}, {shellfish}, {len(affinities)}, {len(pairs)}}},')
        affinities += pairs
    lines += ['};', 'const AffinityRow kAffinities[] = {']
    lines += [f'    {{{i}, {p}}},' for i, p in affinities] or ['    {0, 0},']
    lines += ['};', 'const RodRow kRods[] = {']
    lines += [f'    {{{r}, {s}, {l}}},' for r, s, l in data['phoenix_fish_rods.tsv']]
    lines.append('};')
    return '\n'.join(lines) + '\n'


def main(argv) -> int:
    root = pathlib.Path(__file__).resolve().parent.parent
    check = argv[1:2] == ['--check']
    if len(argv) != (3 if check else 1):
        print('usage: gen_fishing.py [--check DATA_DIR]', file=sys.stderr)
        return 2
    folder = pathlib.Path(argv[2]) if check else root / 'data'
    try:
        data = load_folder(folder)
        text = generate(data)
    except (OSError, ValueError) as error:
        print(f'gen_fishing: {error}', file=sys.stderr)
        return 1
    counts = f'{len(data["phoenix_fish.tsv"])} catches, {len(data["phoenix_fish_areas.tsv"])} areas'
    if check:
        print(f'fishing: {counts} in {folder} pass')
        return 0
    out = root / 'src' / 'generated' / 'fishing.inc'
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding='utf-8')
    print(f'fishing: {counts} -> {out}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main(sys.argv))
