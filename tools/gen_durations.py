#!/usr/bin/env python3
"""Generate src/generated/spell_durations.inc from data/phoenix_spell_durations.tsv (tools/phoenix/durations.lua), in
spell order for the plugin's binary search. With --check DIR, check DIR's file by the same rules and write nothing:
refresh.sh does, before it copies a refresh into data/."""
import pathlib
import sys

FILE = 'phoenix_spell_durations.tsv'
HEADER = 'spell\tseconds'
LIMIT = 0xFFFF  # the plugin keeps both as 16 bits


class DataError(ValueError):
    pass


def parse(text: str) -> list:
    """(spell, seconds) rows."""
    lines = text.splitlines()
    if not lines or lines[0] != HEADER:
        raise DataError(f'{FILE}: the header must be ' + HEADER.replace('\t', ', '))
    rows = []
    for number, line in enumerate(lines[1:], start=2):
        fields = line.split('\t')
        if len(fields) != 2 or not all(f.isdigit() and 0 < int(f) <= LIMIT for f in fields):
            raise DataError(f'{FILE} line {number}: a spell and its seconds, each 1 to {LIMIT}')
        spell, seconds = map(int, fields)
        if rows and spell <= rows[-1][0]:
            raise DataError(f'{FILE} line {number}: spell {spell} after {rows[-1][0]}, out of order')
        rows.append((spell, seconds))
    return rows


def generate(rows: list) -> str:
    lines = [f'// Generated by tools/gen_durations.py from data/{FILE}. Do not edit.']
    lines += [f'    {{{spell}, {seconds}}},' for spell, seconds in rows]
    return '\n'.join(lines) + '\n'


def main(argv) -> int:
    root = pathlib.Path(__file__).resolve().parent.parent
    check = argv[1:2] == ['--check']
    if len(argv) != (3 if check else 1):
        print('usage: gen_durations.py [--check DATA_DIR]', file=sys.stderr)
        return 2
    data = pathlib.Path(argv[2]) if check else root / 'data'
    try:
        rows = parse((data / FILE).read_text(encoding='utf-8'))
    except (OSError, DataError) as error:
        print(f'gen_durations: {error}', file=sys.stderr)
        return 1
    if check:
        print(f'{FILE}: {len(rows)} rows in {data} pass')
        return 0
    out = root / 'src' / 'generated' / 'spell_durations.inc'
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(generate(rows), encoding='utf-8')
    print(f'{FILE}: {len(rows)} rows -> {out}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main(sys.argv))
